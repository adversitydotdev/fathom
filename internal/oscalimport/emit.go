package oscalimport

import (
	"fmt"
	"strings"
)

const generatedComment = "Generated by `ogrc import` from an OSCAL catalog. Do not edit."

func renderFramework(name, id, created, modified, version, publisher, sourceURI, sourcePath, commit string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "type: framework\n")
	fmt.Fprintf(&b, "id: %s\n", yamlScalar("framework--"+id))
	fmt.Fprintf(&b, "spec_version: 0.1.0\n")
	fmt.Fprintf(&b, "created: %s\n", yamlScalar(created))
	fmt.Fprintf(&b, "modified: %s\n", yamlScalar(modified))
	fmt.Fprintf(&b, "name: %s\n", yamlScalar(name))
	fmt.Fprintf(&b, "publisher: %s\n", yamlScalar(publisher))
	fmt.Fprintf(&b, "version: %s\n", yamlScalar(version))
	fmt.Fprintf(&b, "reproduction: permitted\n")
	fmt.Fprintf(&b, "source:\n")
	fmt.Fprintf(&b, "  format: oscal-catalog\n")
	if sourceURI != "" {
		fmt.Fprintf(&b, "  uri: %s\n", yamlScalar(sourceURI))
	}
	if sourcePath != "" {
		fmt.Fprintf(&b, "  path: %s\n", yamlScalar(sourcePath))
	}
	if commit != "" {
		fmt.Fprintf(&b, "  commit: %s\n", yamlScalar(commit))
	}
	return b.String()
}

func renderRequirement(r requirement) string {
	var b strings.Builder
	fmt.Fprintf(&b, "type: requirement\n")
	fmt.Fprintf(&b, "id: %s\n", yamlScalar(r.id))
	fmt.Fprintf(&b, "spec_version: 0.1.0\n")
	fmt.Fprintf(&b, "created: %s\n", yamlScalar(r.created))
	fmt.Fprintf(&b, "modified: %s\n", yamlScalar(r.modified))
	fmt.Fprintf(&b, "display_id: %s\n", yamlScalar(r.displayID))
	fmt.Fprintf(&b, "name: %s\n", yamlScalar(r.name))
	fmt.Fprintf(&b, "framework_ref: %s\n", yamlScalar("framework--"+r.framework))
	fmt.Fprintf(&b, "class: %s\n", yamlScalar(r.class))
	if r.withdrawn {
		fmt.Fprintf(&b, "withdrawn: true\n")
	}
	if strings.TrimSpace(r.statement) != "" {
		writeProse(&b, 0, "statement", r.statement)
	}
	if len(r.parameters) > 0 {
		fmt.Fprintf(&b, "parameters:\n")
		for _, p := range r.parameters {
			fmt.Fprintf(&b, "  %s:\n", p.key)
			fmt.Fprintf(&b, "    label: %s\n", yamlScalar(p.label))
		}
	}
	if len(r.parts) > 0 {
		fmt.Fprintf(&b, "parts:\n")
		for _, p := range r.parts {
			fmt.Fprintf(&b, "  - id: %s\n", yamlScalar(p.id))
			writeProse(&b, 4, "statement", p.statement)
		}
	}
	if len(r.external) > 0 {
		fmt.Fprintf(&b, "external_references:\n")
		for _, ref := range r.external {
			fmt.Fprintf(&b, "  - source: %s\n", yamlScalar(ref.source))
			fmt.Fprintf(&b, "    description: %s\n", yamlScalar(ref.description))
			if ref.url != "" {
				fmt.Fprintf(&b, "    url: %s\n", yamlScalar(ref.url))
			}
		}
	}
	return b.String()
}

