import { apiMocking, apiOrigin, apiToken } from "@/lib/env";

export async function GET(
  _request: Request,
  context: { params: Promise<{ jobId: string; filename: string }> },
): Promise<Response> {
  const { jobId, filename } = await context.params;

  if (apiMocking) {
    return new Response(`# Mock artifact: ${filename}\n\nGenerated by ${jobId}.\n`, {
      status: 200,
      headers: {
        "Content-Type": filename.endsWith(".json") ? "application/json" : "text/markdown; charset=utf-8",
        "Content-Disposition": `inline; filename="${filename}"`,
      },
    });
  }

  const headers: Record<string, string> = {};
  if (apiToken) headers.Authorization = `Bearer ${apiToken}`;

  const upstream = await fetch(
    `${apiOrigin}/v1/jobs/${encodeURIComponent(jobId)}/files/${encodeURIComponent(filename)}`,
    { headers, cache: "no-store" },
  );

  if (!upstream.ok) {
    return new Response(await upstream.text(), {
      status: upstream.status,
      headers: { "Content-Type": upstream.headers.get("content-type") ?? "text/plain" },
    });
  }

  const contentType = upstream.headers.get("content-type") ?? "application/octet-stream";
  return new Response(upstream.body, {
    status: 200,
    headers: {
      "Content-Type": contentType,
      "Content-Disposition": `inline; filename="${filename}"`,
    },
  });
}
